public class string {
    public static void main(String[] args) {
        // concatenation, ChatAt, Length, Replace
        String firstName = "John";
        String lastName = "Doe";
        System.out.println(firstName + " " + lastName); // Concatenation
        System.out.println(firstName.charAt(2)); // J
        System.out.println(lastName.length()); // 4
        System.out.println(firstName.length()); // 4
        System.out.println(firstName.replace("J", "K")); // Kohn
    }   
}
